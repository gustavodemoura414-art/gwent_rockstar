  static List<GameCard> buildShuffledDeck(
    RockStarDeck deckType,
    String prefix,
  ) {
    final rng = Random();
    final cards = cardsForDeck(deckType)
        .asMap()
        .entries
        .map(
          (e) => e.value.copyWith(
            id: '${prefix}_${deckType.name}_${e.key}_${e.value.id}',
            imageAsset: e.value.resolvedImageAsset,
          ),
        )
        .toList()
      ..shuffle(rng);

    return cards;
  }
